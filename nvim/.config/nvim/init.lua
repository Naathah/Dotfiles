-- Load colors dynamically generated by Noctalia
local function set_transparent()
	local groups = {
		"Normal", "NormalNC", "EndOfBuffer", "NormalFloat",
		"FloatBorder", "SignColumn", "StatusLine", "StatusLineNC",
		"TabLine", "TabLineFill", "TabLineSel", "ColorColumn",
		"CursorLine", "CursorLineNr" -- Added CursorLineNr just to be safe
	}
	for _, g in ipairs(groups) do
		-- Force background to none, but keep whatever foreground color the theme set
		local hl = vim.api.nvim_get_hl(0, { name = g })
		hl.bg = "none"
		hl.ctermbg = "none"
		vim.api.nvim_set_hl(0, g, hl)
	end
	
	local tab_hl = vim.api.nvim_get_hl(0, { name = "TabLineFill" })
	tab_hl.bg = "none"
	tab_hl.fg = "#767676"
	vim.api.nvim_set_hl(0, "TabLineFill", tab_hl)
end

-- Force transparency to apply AFTER the colorscheme loads
vim.api.nvim_create_autocmd("ColorScheme", {
	pattern = "*",
	callback = set_transparent,
})

