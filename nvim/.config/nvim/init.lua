-- Format on save (Only for Python and Lua)
vim.api.nvim_create_autocmd("BufWritePre", {
	group = augroup,
	pattern = { "*.lua", "*.py" },
	callback = function(args)
		if vim.bo[args.buf].buftype ~= "" or not vim.bo[args.buf].modifiable or vim.api.nvim_buf_get_name(args.buf) == "" then return end
		local has_efm = false
		for _, c in ipairs(vim.lsp.get_clients({ bufnr = args.buf })) do
			if c.name == "efm" then
				has_efm = true
				break
			end
		end
		if not has_efm then return end
		pcall(vim.lsp.buf.format, {
			bufnr = args.buf,
			timeout_ms = 2000,
			filter = function(c) return c.name == "efm" end,
		})
	end,
})

